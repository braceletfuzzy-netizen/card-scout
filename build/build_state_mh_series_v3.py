# BUILD + TEST state_mh_series_v3.json — THE LETTER-GATE CLEAN-UP (lanes 1+2+3 applied).
# Lane-1: real Census PEP per-year pops (populations_states_v1.jsonl / populations_cities_v2.jsonl) replace
#         the static state-approx dict and CITY_POP_APPROX. 2026/2027 state-years have NO published PEP
#         vintage -> honest-null (excluded, flagged), never a carried-forward figure.
# Lane-2: OKC/Pittsburgh gap was NOT a year-label or agency-name mismatch — both cities were simply absent
#         from every crime source file (wave pulls used fixed city lists). crime_wide_c.jsonl (this run's CDE
#         pull, ORIs PAPPD0000 / OK0550600) fills them; _merge_murders.py now includes crime_wide_c.
# Lane-3: Pittsburgh series = PAPPD0000 CDE HOM 2019-2025, with an honest months-present guard:
#         2019 (11/12) and 2021 (0 murders over 8/12) EXCLUDED as partial/non-reporting, never passed as counts.
# Months-guard: applied where months metadata exists (crime_wide* months_reported/months_present; wave-1
#         'Sum of X/12' notes). NOLA 2025 = 0/12 non-reporting -> excluded (the 0 was poisoning the arc).
# Rows lacking month metadata (city-sourced annual counts) keep prior treatment.
import json, re, statistics, datetime

B = 'C:/Users/J/Documents/LLM/cardscout-2.0/For You/PolyScout/build/'

HDR = ('STATE-MH-SERIES v3 REPRODUCIBILITY HEADER — LETTER-GATE CLEAN-UP. Built ' + datetime.date.today().isoformat() +
       ' by build_state_mh_series_v3.py from: state_mh_series_v2.jsonl (v1+v2 budget rows verbatim), '
       'populations_states_v1.jsonl (Census PEP vintage-2025 NST-EST2025-ALLDATA SUMLEV-040 2020-2025 + vintage-2019 '
       'sub-est2019_all SUMLEV-040 2019), populations_cities_v2.jsonl (PEP SUMLEV-162, 2019 from sub-est2019_all, '
       '2020-2025 from sub-est2025_<fips>, STL-2024 holefill from sub-est2024_29), murders_all_v1.json regenerated by '
       '_merge_murders.py with crime_wide_c.jsonl added (Lane-2 fill: Pittsburgh PAPPD0000, Oklahoma City OK0550600 '
       '— root cause of the n=0: cities absent from source files, NOT year-label/agency-name; plus Detroit MI8234900 '
       '2019-2025 full-series holefill from the same keyless CDE lane). Months-guard excludes '
       'partial-year/non-reporting CDE city-years where months metadata exists (Pittsburgh 2019=11/12, 2021=0/8; NOLA '
       '2025=0/12). 2026-2027 state budget-years are excluded-honest because Census PEP vintage-2026 is not yet '
       'published (no static-pop carry-forward; approx-flag law). The static-approx state-pop dict and '
       'CITY_POP_APPROX are REMOVED — no approx-pop pairs remain in the pooled test.')

# ---------- budget rows (v2 file, verbatim) ----------
rows = [json.loads(l) for l in open(B + 'state_mh_series_v2.jsonl', encoding='utf-8') if l.strip()]
state_vals = {}
for r in rows:
    st = r.get('state') or r.get('st')
    fy = r.get('fiscal_year') or r.get('year')
    v = r.get('state_mh_budget_usd')
    if not st or not fy or not v:
        continue
    try:
        y = int(str(fy)[-4:])
    except Exception:
        continue
    state_vals.setdefault(st, {})[y] = (v, r.get('value_kind', ''))

# ---------- real state pops (PEP per-year) ----------
spop = {}
for l in open(B + 'populations_states_v1.jsonl', encoding='utf-8'):
    if not l.strip():
        continue
    r = json.loads(l)
    if r.get('record') == 'reproducibility_header':
        continue
    spop[(r['state_abbr'], r['year'])] = (r['population'], r.get('source_vintage', ''))

# ---------- real city pops (PEP per-year; banked files first, v2 file overrides approx lanes) ----------
CITY_FILE_NAME = {'NYC': 'New York'}
city_pop = {}
pop_files = ('population_series_v1.jsonl', 'nola_houston_pair_v1.jsonl',
             'populations_wide_v1.jsonl', 'populations_cities_v2.jsonl')
for f in pop_files:
    for l in open(B + f, encoding='utf-8'):
        if not l.strip():
            continue
        r = json.loads(l)
        try:
            c = (r.get('city') or '').strip()
            y = int(str(r.get('year'))[:4])
            p = r.get('population')
            if p and c and y:
                city_pop[(c, y)] = (int(p), r.get('source_vintage') or r.get('anchor_or_estimate') or 'banked')
        except Exception:
            pass

city_of_state = {'NY': 'NYC', 'MO': 'St. Louis', 'PA': 'Pittsburgh', 'TN': 'Memphis',
                 'OH': 'Cincinnati', 'MI': 'Detroit', 'OK': 'Oklahoma City', 'LA': 'New Orleans'}

# ---------- murders with months metadata ----------
murders = json.load(open(B + 'murders_all_v1.json', encoding='utf-8'))
murders_meta = {}   # (city, year) -> (murders, months_present or None, source_note)
for f in ('crime_series_wave1.jsonl', 'crime_series_wave1b.jsonl', 'crime_series_wave2_holefill.jsonl',
          'crime_wide.jsonl', 'crime_wide_b.jsonl', 'crime_wide_c.jsonl'):
    try:
        for l in open(B + f, encoding='utf-8'):
            if not l.strip():
                continue
            r = json.loads(l)
            c = (r.get('city') or '').strip()
            y = r.get('year')
            if not y or r.get('murders') is None:
                continue
            y = int(y)
            mp = r.get('months_present', r.get('months_reported'))
            if mp is None:
                m = re.search(r'Sum of (\d+)/12', str(r.get('notes') or ''))
                if m:
                    mp = int(m.group(1))
            key = (c, y)
            cur = murders_meta.get(key)
            # prefer the row with months metadata; else max (same dedupe law as _merge_murders)
            if cur is None or (mp is not None and cur[1] is None) or (mp is not None and cur[1] is not None and r['murders'] > cur[0]):
                murders_meta[key] = (r['murders'], mp, str(r.get('source_refs') or [''])[0][:80])
    except FileNotFoundError:
        pass

def murders_for(canon_city, y):
    """resolve via murders_all_v1 (canon names) + months guard."""
    m = murders.get(f'{canon_city}|{y}')
    if m is None:
        return None, None, 'no-entry'
    meta = murders_meta.get((canon_city, y))
    mp = meta[1] if meta else None
    if mp is not None and mp < 12:
        return None, mp, f'partial/non-reporting guard: only {mp}/12 CDE months'
    return m, mp, 'ok'

def corr(x, yv):
    if len(x) < 3 or len(set(yv)) < 2:
        return None
    mx, my = statistics.mean(x), statistics.mean(yv)
    num = sum((a - mx) * (b - my) for a, b in zip(x, yv))
    den = (sum((a - mx) ** 2 for a in x) * sum((b - my) ** 2 for b in yv)) ** 0.5
    return round(num / den, 3) if den else None

v3 = {'record': 'state_mh_series_v3', 'reproducibility_header': HDR, 'built': datetime.date.today().isoformat(),
      'per_state': {}, 'test': {}}
print('=== THE EXPANDED MULTI-STATE v3 (LANES 1+2+3 APPLIED — real PEP pops, months-guard, gap-fill) ===')
all_pairs = []
for st in sorted(state_vals):
    if st not in city_of_state:
        continue
    c = city_of_state[st]
    fname = CITY_FILE_NAME.get(c, c)
    lane, arc = [], []
    for y, (v, kind) in sorted(state_vals[st].items()):
        sp = spop.get((st, y))
        mur, mp, mcls = murders_for(c, y)
        entry = {'fiscal_year': y, 'state_mh_budget_usd': v, 'value_kind': kind,
                 'state_pop': sp[0] if sp else None, 'state_pop_vintage': sp[1] if sp else None,
                 'murders': mur, 'cde_months_present': mp}
        reasons = []
        if sp is None:
            reasons.append('no published PEP vintage for this year (honest-null; no carry-forward)')
        if mur is None:
            reasons.append(f'murders unavailable: {mcls}' if mcls != 'ok' else 'murders unavailable')
        cp = None
        if mur is not None:
            cp = city_pop.get((fname, y)) or city_pop.get((c, y))
        if mur is not None and cp is None:
            reasons.append('city-pop missing (honest-null)')
        if reasons:
            entry['included_in_test'] = False
            entry['exclusion_reason'] = '; '.join(reasons)
            arc.append(entry)
            continue
        mh_pc = v / sp[0]  # plain dollars-per-resident: every state_mh_budget_usd in the file is full USD
        rate = mur / cp[0] * 100000
        entry.update({'mh_usd_per_resident': round(mh_pc, 2),
                      'city': c, 'city_pop': cp[0], 'city_pop_vintage': cp[1],
                      'murder_rate_per_100k': round(rate, 2),
                      'included_in_test': True})
        lane.append((y, mh_pc, rate))
        arc.append(entry)
    v3['per_state'][st] = {'city': c, 'years': arc, 'n_tested': len(lane)}
    if lane:
        all_pairs.append((st, c, lane))
    if len(lane) >= 3:
        r = corr([p[1] for p in lane], [p[2] for p in lane])
        print(f' {c}/{st}: n={len(lane)} | same-year r = {r} span {lane[0][0]}-{lane[-1][0]} (100% real-PEP pops, no approx flags)')
        for lag in (1, 2):
            ll = [(lane[i][1], lane[i + lag][2]) for i in range(len(lane) - lag)]
            if len(ll) >= 3:
                print(f'   t vs t+{lag} (n={len(ll)}): r = {corr([a[0] for a in ll], [a[1] for a in ll])}')
    else:
        print(f' {c}/{st}: n={len(lane)} | TOO-THIN (honest)')

v3['test']['per_state'] = {st: {'n': len(lane),
                                'same_year_r': corr([p[1] for p in lane], [p[2] for p in lane]),
                                'span': [lane[0][0], lane[-1][0]]} for st, c_, lane in all_pairs}

# pooled within-state (demeaned per city)
per_city = {}
for st, c, lane in all_pairs:
    if len(lane) >= 3:
        per_city.setdefault(c, lane)
dm = []
for c, lane in per_city.items():
    mx = statistics.mean([p[1] for p in lane]); my = statistics.mean([p[2] for p in lane])
    for p in lane:
        dm.append((p[1] - mx, p[2] - my, p[0], c))
r_pooled = corr([a[0] for a in dm], [a[1] for a in dm])
print()
print(f'THE POOLED-WITHIN-STATE (demeaned, n={len(dm)}, cities={sorted(per_city)}): r = {r_pooled}')
v3['test']['pooled_within_state'] = {'n': len(dm), 'cities': sorted(per_city), 'r': r_pooled,
                                     'pops': '100% Census PEP per-year (approx-flags removed)'}

json.dump(v3, open(B + 'state_mh_series_v3.json', 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
print('wrote state_mh_series_v3.json')
